class FakeResponse:
    def __init__(self, content):
        self.content = content

    def json(self):
        return {"choices": [{"message": {"content": self.content}, "finish_reason": "stop"}], "provider": "Fake"}


@contextlib.contextmanager
def patched_eval_answers(content):
    """eval_answers.answer() with its HTTP call replaced: records every request body."""
    import eval_answers as EA

    bodies = []
    saved = EA.post_with_retry, EA._api_key
    EA.post_with_retry = lambda url, body, key: (bodies.append(copy.deepcopy(body)), FakeResponse(content))[1]
    EA._api_key = lambda name: "test-key"
    try:
        yield EA, bodies
    finally:
        EA.post_with_retry, EA._api_key = saved


