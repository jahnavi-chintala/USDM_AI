def reply(claims=(), status="answered", answer="", conflicts=(), values=()) -> dict:
    return {"claims": list(claims), "conflicts": list(conflicts), "values": list(values), "answer": answer,
            "status": status}


def claim(text, *quotes, derived=False, derivation="") -> dict:
    return {"text": text, "quotes": [{"block": b, "quote": q} for b, q in quotes], "derived": derived,
            "derivation": derivation}


