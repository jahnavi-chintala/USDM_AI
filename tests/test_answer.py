def test_retry_flow() -> None:
    res, client = run([BAD_CMP, GOOD])
    assert len(client.bodies) == 2 and res["status"] == "answered" and res["verification"]["retried"]
    msgs = client.bodies[1]["messages"]
    assert [m["role"] for m in msgs] == ["system", "user", "assistant", "user"]
    assert "comparator mismatch" in msgs[3]["content"] and "<400" in msgs[3]["content"]
    assert json.loads(msgs[2]["content"])["claims"][0]["text"].startswith("Platelet count <400")
    assert res["verification"]["first_attempt_problems"] and not res["verification"]["problems"]
    # the retry still fails: unverified claim remains -> partial; the better attempt is kept
    res, client = run([BAD_CMP, BAD_CMP])
    assert len(client.bodies) == 2 and res["status"] == "partial" and not res["claims"][0]["verified"]
    # an unparseable first reply is retried; an unparseable retry keeps the first attempt
    res, _ = run(["I think the answer is 400.", GOOD])
    assert res["status"] == "answered" and "not valid JSON" in res["verification"]["first_attempt_problems"][0]
    res, _ = run([BAD_CMP, "{broken"])
    assert res["status"] == "partial" and res["claims"][0]["text"].startswith("Platelet count <400")
    res, _ = run(["nothing", "still nothing"])
    assert res["status"] == "partial" and res["answer"] == "" and res["verification"]["problems"]


def test_conflict_passthrough() -> None:
    conflict = reply([claim("The synopsis requires a platelet count <400 × 10^9/L.",
                            (2, "platelet count <400 × 10^9/L at screening")),
                      claim("Inclusion criterion 5 requires a platelet count ≤400 × 10^9/L.",
                            (3, "5. Platelet count ≤400 × 10 9 /L"))],
                     status="conflict",
                     answer="The blocks disagree: the synopsis says <400 × 10^9/L [2], the inclusion criteria "
                            "say ≤400 × 10^9/L [3].",
                     conflicts=[{"claims": [0, 1], "note": "<400 (synopsis) vs ≤400 (section 5.1)"}])
    res, client = run([conflict])
    assert len(client.bodies) == 1 and res["status"] == "conflict"
    cf = res["conflicts"][0]
    assert cf["verified"] and cf["claims"] == [0, 1] and [q["block"] for q in cf["quotes"]] == [2, 3]
    # a conflict claimed without a conflicts entry is a schema problem -> retried
    res, client = run([{**conflict, "conflicts": []}, conflict])
    assert len(client.bodies) == 2 and res["status"] == "conflict"


