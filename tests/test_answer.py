def test_quote_levels() -> None:
    b = blocks()
    b2, b3, b5 = b[1], b[2], b[4]
    assert A.locate(A.clean_quote("Absolute neutrophil count ≥1.5 × 10^9/L"), b3)[:2] == ("exact", "document")
    # flattened superscript, caret, case, curly quotes around it, en dash / whitespace variants
    assert A.locate(A.clean_quote("“Platelet count ≤400 × 10^9/L”"), b3)[0] == "normalised"
    assert A.locate(A.clean_quote("platelet  count ≤ 400 x 10⁹/L"), b3)[0] == "normalised"
    assert A.locate(A.clean_quote("Visit window (days) | -28 to -1 | ±3"), b[3])[0] == "exact"
    assert A.locate(A.clean_quote("Visit window (days) | –28 to –1 | ± 3"), b[3])[0] == "normalised"
    # elided: in order, inside one passage
    assert A.locate(A.clean_quote("Participants must have a platelet count … at screening"), b2)[0] == "elided"
    assert A.locate(A.clean_quote("at screening … Participants must have"), b2)[0] is None  # wrong order
    # too short to verify
    assert A.locate("X", b[3])[0] is None and A.locate("0 or 1", b3)[0] is None
    # Day -1 is not Day 1: hyphens next to digits are never dropped
    assert A.locate(A.clean_quote("Visit window (days) | -28 to 1"), b[3])[0] is None
    # AI-generated figure parts
    assert A.locate("Cohort A: 40 participants", b5)[:2] == ("exact", "ai_generated")
    assert A.locate("Cohort A receives 12 mg/kg", b5)[1] == "ai_generated"
    assert A.locate("A second paragraph of the description", b5)[1] == "ai_generated"
    assert A.locate("Cohort A; Cohort B; Randomization 1:1", b5)[:2] == ("exact", "document")
    text, has_ai = A.split_ai("Figure (page 9)\n*Figure description generated by x/y; verify against the image.*\n\n"
                              "It shows 3 arms.\n\nText in figure (OCR):\nArm A | Arm B")
    assert has_ai and "3 arms" not in text and "Arm A | Arm B" in text


def test_quote_fuzzy_and_guards() -> None:
    b2 = blocks()[1]
    lvl, src, sim, matched = A.locate("Zorbimab 12 mg/kg is given intravenusly every 3 weeks (Q3W)", b2)
    assert lvl == "fuzzy" and src == "document" and sim >= 0.95 and "intravenously" in matched
    # never fuzzy across a number, a comparator, a negation, another word or a short-word typo
    for bad in ("Zorbimab 15 mg/kg is given intravenously every 3 weeks (Q3W)",
                "Participants must have a platelet count ≤400 × 10^9/L at screening",
                "Participants must not have a platelet count <400 × 10^9/L at screening",
                "Participants may have a platelet count <400 × 10^9/L at screening",
                "Zorbimab 12 mg/kg is givn intravenously every 3 weeks (Q3W)"):
        assert A.locate(bad, b2)[0] is None, bad
    assert not A.fuzzy_safe("female participants must have", "male participants must have")
    assert not A.fuzzy_safe("hypotension grade", "hypertension grade")
    assert A.fuzzy_safe("participants, must have the", "participants must have")
    # a table quote may skip one cell boundary, not an empty cell (columns would shift)
    assert A.fuzzy_safe("glorp score x x", "glorp score | x x")
    assert not A.fuzzy_safe("glorp score x x", "glorp score | | x x")
    sched = A.VBlock(1, "| Activity | V1 | V2 | V3 |\n| Physical examination of the participant |  | X | X |")
    assert A.locate("Physical examination of the participant X X", sched)[0] is None  # skips the empty V1 cell
    assert A.locate("| Physical examination of the participant |  | X | X |", sched)[0] == "exact"
    sched = A.VBlock(1, "| Activity | V1 | V2 |\n| Physical examination of the participant | X | X |")
    assert A.locate("Physical examination of the participant X X", sched)[0] == "fuzzy"


