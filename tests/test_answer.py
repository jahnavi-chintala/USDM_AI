def test_offline_refusal() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        cache = Path(tmp) / A.CACHE_NAME
        run([GOOD], cache=cache)
        client = FakeClient([GOOD])
        with env(OPENROUTER_OFFLINE="1"):
            g = A.GroundedAnswerer("fake/model", cache, client)
            assert g.run(QUESTION, make_context())["status"] == "answered"  # cached: fine offline
