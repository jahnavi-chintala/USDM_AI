        row = next(ln for ln in out.splitlines() if ln.startswith("SYN "))
        assert row.split()[1:4] == ["2", "3.0", "66.7"], row  # 2 answers, 6 statements: 4 verified, 1 derived, 1 unverified
        assert "answers judged 2, the same prose confirmed via the judge cache 2" in out
        assert "contradicted fact flagged by verification: 1/1 (100%)" in out
        assert "contradicted facts -> closest statement: unverified 1" in out
        assert "judge extra claims (2) -> closest statement: verified 1, derived_ok 1" in out
        assert "Q1 fact f2: unverified" in out and "21 years" not in out  # no protocol text without --show-text
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            A.main(["verify-report", str(root / "v_SYN"), "--judge-run", str(root / "j_SYN"), "--show-text"])
        assert "21 years" in buf.getvalue()


