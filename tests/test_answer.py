def test_caching_and_keys() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        cache = Path(tmp) / A.CACHE_NAME
        res1, c1 = run([BAD_CMP, GOOD], cache=cache)
        assert len(c1.bodies) == 2 and len(json.loads(cache.read_text(encoding="utf-8"))) == 2
        res2, c2 = run([], cache=cache)  # a fresh instance replays both calls from disk
        assert c2.bodies == [] and res2["meta"]["cached"] and res2["meta"]["api_calls"] == 0
        assert {k: res2[k] for k in ("status", "claims", "verification")} == \
               {k: res1[k] for k in ("status", "claims", "verification")}
        _, c3 = run([GOOD], question=QUESTION + " ", cache=cache)  # another question: another key
        assert len(c3.bodies) == 1
        other = make_context()
        other.blocks[2].text += "\n9. Extra criterion."
        _, c4 = run([GOOD], cache=cache, ctx=other)  # another context: another key
        assert len(c4.bodies) == 1
        g = A.GroundedAnswerer("fake/model", cache)
        assert g.key("ctx", "q") != A.GroundedAnswerer("other/model", cache).key("ctx", "q")
        assert g.key("ctx", "q") != g.key("ctx", "q", ["x", "feedback"])


