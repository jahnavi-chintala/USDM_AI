class FakeClient:
    """Scripted chat completions; records every request body. A reply may be a dict (sent as JSON
    content), a string (raw content) or an exception (raised)."""

    def __init__(self, replies):
        self.replies = list(replies)
        self.bodies = []

    def complete(self, body: dict) -> dict:
        self.bodies.append(copy.deepcopy(body))
        if not self.replies:
            raise AssertionError("unexpected API call")
        r = self.replies.pop(0)
        if isinstance(r, Exception):
            raise r
        content = r if isinstance(r, str) else json.dumps(r, ensure_ascii=False)
        return {"choices": [{"message": {"content": content}, "finish_reason": "stop"}], "provider": "Fake",
                "usage": {"prompt_tokens": 1, "completion_tokens": 1}}


@contextlib.contextmanager
def env(**values):
    old = {k: os.environ.get(k) for k in values}
    try:
        for k, v in values.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        yield
    finally:
        for k, v in old.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def run(replies, question=QUESTION, cache=None, ctx=None):
    client = FakeClient(replies)
    with env(OPENROUTER_OFFLINE=None):
        res = A.GroundedAnswerer("fake/model", cache, client).run(question, ctx or make_context())
    return res, client


def blocks():
    return A.context_blocks(make_context())


def checked(obj, question=QUESTION):
    o, problems = A.coerce(obj)
    return A.verify(o, problems, blocks(), question)


