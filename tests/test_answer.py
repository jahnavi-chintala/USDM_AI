def test_units_and_dropped_comparators() -> None:
    q = [A.norm("Zorbimab 12 mg/kg is given intravenously every 3 weeks (Q3W).")]
    assert any("unit 'mg'" in i for i in A.check_mentions(A.mentions("Zorbimab 12 mg Q3W"), q))
    assert not A.check_mentions(A.mentions("Zorbimab 12 mg/kg every 3 weeks"), q)
    assert any("unit 'day'" in i for i in A.check_mentions(A.mentions("every 3 days"), q))
    assert any("not in the claim's quotes" in i for i in A.check_mentions(A.mentions("Zorbimab 1200 mg/kg"), q))
    dropped = A.check_mentions(A.mentions("ANC 1.5 × 10^9/L"), [A.norm("Absolute neutrophil count ≥1.5 × 10^9/L")])
    assert dropped and "comparator dropped" in dropped[0]
    # conversions are not copies
    assert A.check_mentions(A.mentions("ANC ≥1500/µL"), [A.norm("ANC ≥1.5 × 10^9/L")])
    # flattened superscripts of area units
    assert not A.check_mentions(A.mentions("BMI 18.5 to 30.0 kg/m²"), [A.norm("a body mass index of 18.5 to 30.0 kg/m 2")])
    assert [m.unit for m in A.mentions("30.0 kg/m 2")] == ["kg/m2"]
    # table windows: the unit sits in the row label, the visit name in the header row (a second quote)
    row, header = A.norm("| Visit window (days) | -28 to -1 | ±3 | ±2 |"), A.norm("| Procedure | Screening | C1D1 | C1D8 |")
    assert not A.check_mentions(A.mentions("C1D8 window ±2 days"), [row, header])
    assert any("number 8 " in i for i in A.check_mentions(A.mentions("C1D8 window ±2 days"), [row]))


def test_derived_values() -> None:
    good = reply([claim("The total planned enrolment is 64 participants (derived: 40 + 24).",
                        (6, "Approximately 40 participants will be enrolled in Cohort A and 24 participants in Cohort B"),
                        derived=True, derivation="40 + 24 = 64")],
                 answer="In total 64 participants are planned (40 in Cohort A and 24 in Cohort B) [6].")
    c = checked(good, "How many participants are planned in total?")
    assert c.claims[0]["verified"] and not c.critical and not c.numbers_unverified
    wrong = copy.deepcopy(good)
    wrong["claims"][0]["derivation"] = "40 + 24 = 66"
    wrong["claims"][0]["text"] = "The total is 66 participants."
    c = checked(wrong)
    assert not c.claims[0]["verified"] and any("arithmetic" in i for i in c.claims[0]["issues"])
    unlabelled = copy.deepcopy(good)
    unlabelled["claims"][0].update(derived=False, derivation="")
    c = checked(unlabelled)
    assert not c.claims[0]["verified"] and any("64" in i for i in c.claims[0]["issues"])
    no_inputs = copy.deepcopy(good)
    no_inputs["claims"][0]["derivation"] = "40 + 25 = 65"
    c = checked(no_inputs)
    assert any("input 25" in i for i in c.claims[0]["issues"])


